function Resolve-IosBooleanValue {
    <#
    .SYNOPSIS
        Converts CIS recommendation text/value into a boolean used by iOS template properties.
    #>
    param(
        [string]$SettingValue,
        [string]$Recommendation
    )

    $candidates = @($SettingValue, $Recommendation) | Where-Object { -not [string]::IsNullOrWhiteSpace($_) }
    foreach ($raw in $candidates) {
        $value = $raw.Trim().ToLowerInvariant()

        if ($value -match '^(enabled|checked|true|yes|allow|allowed|on|required)$') { return $true }
        if ($value -match '^(disabled|unchecked|false|no|block|blocked|off|not configured)$') { return $false }

        if ($value -match '^(enabled|checked)\s*:') { return $true }
        if ($value -match '^(disabled|unchecked)\s*:') { return $false }

        if ($value -match '\b(enable|allow|required)\b' -and $value -notmatch '\b(disable|block|not\s+allow|not\s+allowed)\b') { return $true }
        if ($value -match '\b(disable|block|blocked|not\s+allow|not\s+allowed)\b') { return $false }

        if ($value -match '^1$') { return $true }
        if ($value -match '^0$') { return $false }
    }

    return $null
}

function Get-IosTemplatePropertyName {
    <#
    .SYNOPSIS
        Maps recommendation/setting text to iosGeneralDeviceConfiguration properties.
    #>
    param(
        [string]$SettingName,
        [string]$GpSettingName,
        [string]$Recommendation
    )

    $combined = @($SettingName, $GpSettingName, $Recommendation) -join ' '
    $t = $combined.ToLowerInvariant()

    if ($t -match 'game\s*center\s*friends|friends.*game\s*center') { return 'gamingBlockGameCenterFriends' }
    if ($t -match '\bmultiplayer\b') { return 'gamingBlockMultiplayer' }
    if ($t -match 'game\s*center') { return 'gameCenterBlocked' }

    if ($t -match 'managed\s+documents?.*unmanaged\s+apps?|unmanaged\s+destination') { return 'documentsBlockManagedDocumentsInUnmanagedApps' }
    if ($t -match 'unmanaged\s+documents?.*managed\s+apps?') { return 'documentsBlockUnmanagedDocumentsInManagedApps' }

    if ($t -match 'air\s*drop.*unmanaged') { return 'airDropForceUnmanagedDropTarget' }
    if ($t -match 'air\s*drop') { return 'airDropBlocked' }

    if ($t -match 'automatic\s+downloads?.*app\s*store|app\s*store.*automatic\s+downloads?') { return 'appStoreBlockAutomaticDownloads' }
    if ($t -match 'in[-\s]*app\s+purchases?') { return 'appStoreBlockInAppPurchases' }
    if ($t -match 'app\s*store.*(ui\s*app\s*installation|app\s*installation|installation)') { return 'appStoreBlockUIAppInstallation' }
    if ($t -match 'app\s*store.*password|required\s+password') { return 'appStoreRequirePassword' }
    if ($t -match 'app\s*store') { return 'appStoreBlocked' }

    if ($t -match 'ibooks') { return 'iBooksStoreBlocked' }

    return ''
}

function Get-IosTemplateFieldUpdatesFromSettings {
    <#
    .SYNOPSIS
        Builds iosGeneralDeviceConfiguration property updates from parsed CIS settings.
    #>
    param([array]$Settings)

    $updates = @{}
    $unmapped = @()

    foreach ($setting in @($Settings)) {
        $propertyName = Get-IosTemplatePropertyName -SettingName $setting.SettingName -GpSettingName $setting.GpSettingName -Recommendation $setting.Recommendation
        if (-not $propertyName) {
            $unmapped += $setting
            continue
        }

        $resolvedBool = Resolve-IosBooleanValue -SettingValue $setting.SettingValue -Recommendation $setting.Recommendation
        if ($null -eq $resolvedBool) {
            $unmapped += $setting
            continue
        }

        $updates[$propertyName] = [bool]$resolvedBool
    }

    return [pscustomobject]@{
        Updates = $updates
        Unmapped = @($unmapped)
    }
}

