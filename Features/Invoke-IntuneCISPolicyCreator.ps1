    function Update-SelectionCount {
        $items = $script:previewItems
        if (-not $items) { $txtSelectionCount.Text = ''; return }
        $sel         = @($items | Where-Object { $_.Selected }).Count
        $tot         = @($items).Count
        $manualCount = @($items | Where-Object { $_.IsManual }).Count
        $policies    = @($items | Where-Object { $_.Selected } | ForEach-Object { $_.PolicyName } | Sort-Object -Unique).Count
        $filterText  = $txtFilter.Text.Trim()
        $filterInfo  = if ($filterText) { " | showing $(@($dgPolicies.ItemsSource).Count) matching '$filterText'" } else { '' }
        $manualInfo  = if ($manualCount -gt 0) { " | $manualCount manual" } else { '' }
        $txtSelectionCount.Text = "$sel of $tot settings selected ($policies policies)$manualInfo$filterInfo"
    }

    function Update-Preview {
        $mdPath = $txtMdPath.Text.Trim()
        if (-not $mdPath -or -not (Test-Path $mdPath)) {
            $dgPolicies.ItemsSource = $null
            $txtInfo.Text = 'Select a Markdown file to see policy summary.'
            Update-SelectionCount
            return
        }

        try {
            # Use the core Parse-MdFile function (same function used in CLI mode)
            $script:parsedData = Parse-MdFile -Path $mdPath
        } catch {
            $txtInfo.Text = "Error parsing file: $($_.Exception.Message)"
            return
        }

        $profileLevel = ($cmbProfileLevel.SelectedItem).Tag

        $filteredRecs = switch ($profileLevel) {
            'L1'  { $script:parsedData | Where-Object { $_.Followed -eq 'Yes' -or $_.Origin -imatch 'twoday' } }
            'L2'  { $script:parsedData }
            'All' { $script:parsedData }
        }

        $script:previewItems = [System.Collections.ObjectModel.ObservableCollection[RecItem]]::new()
        foreach ($rec in $filteredRecs) {
            $item               = [RecItem]::new()
            $item.CISRef        = $rec.CISReference
            $item.SettingName   = $rec.SettingName
            $item.SettingValue  = if ($rec.SettingValue) { $rec.SettingValue } else { '-' }
            $item.PolicyName    = $rec.IntunePolicy
            $item.Profile       = $rec.Profile
            $item.Recommendation = $rec.Recommendation
            $item.Notes         = if ($rec.Notes) { $rec.Notes } else { '-' }
            $item.IsManual      = ($rec.Notes -and $rec.Notes -match 'Customer\s+data')
            $item.Selected      = -not $item.IsManual
            $script:previewItems.Add($item)
        }

        $dgPolicies.ItemsSource = $script:previewItems

        $totalRecs     = $script:parsedData.Count
        $filteredCount = ($filteredRecs | Measure-Object).Count
        $policyCount   = @($filteredRecs | ForEach-Object { $_.IntunePolicy } | Sort-Object -Unique).Count

        $txtInfo.Text = "$totalRecs total recommendations | $filteredCount after $profileLevel filter | $policyCount policies"
        Update-SelectionCount
        Apply-TextFilter
    }

    function Apply-TextFilter {
        $filterText = $txtFilter.Text.Trim()
        if (-not $script:previewItems) { return }

        if (-not $filterText) {
            $dgPolicies.ItemsSource = $script:previewItems
        } else {
            $filtered = [System.Collections.ObjectModel.ObservableCollection[RecItem]]::new()
            foreach ($item in $script:previewItems) {
                if ($item.CISRef        -like "*$filterText*" -or
                    $item.SettingName   -like "*$filterText*" -or
                    $item.SettingValue  -like "*$filterText*" -or
                    $item.PolicyName    -like "*$filterText*" -or
                    $item.Recommendation -like "*$filterText*") {
                    $filtered.Add($item)
                }
            }
            $dgPolicies.ItemsSource = $filtered
        }
        Update-SelectionCount
    }

