function Parse-MdFile {
    <#
    .SYNOPSIS
        Parses the CIS Benchmark MD file and extracts all recommendation rows.
    #>
    param([string]$Path)

    $content = Get-Content $Path -Raw
    $lines = $content -split "`n"

    $recommendations = @()
    $currentSection = ''
    $currentSubSection = ''

    foreach ($line in $lines) {
        $line = $line.TrimEnd()

        # Track section headings.
        # Only update $currentSection for app/product-level headings (those containing "Microsoft").
        # Sub-section headings like "2.2.4 Excel Options" or "2.2.4.7 Security" must NOT overwrite
        # the app-level section (e.g. "2.2 Microsoft Excel 2016") because Get-AppProductIdPattern
        # relies on the section name to identify the correct app.
        if ($line -match '^## \d+') {
            $headingText = ($line -replace '^## ', '').Trim()
            if ($headingText -imatch '\bMicrosoft\b') {
                $currentSection = $headingText
            }
        }
        if ($line -match '^### ') {
            $currentSubSection = ($line -replace '^### ', '').Trim()
        }

        # Parse table data rows (start with | and contain "Ensure" or a recommendation or Twoday origin)
        if ($line -match '^\|\s*Ensure\s' -or $line -match '^\|\s*[A-Z].*\|.*\|.*\d+\.\d+' -or ($line -match '^\|' -and $line -imatch '\btwoday\b')) {
            $s = $line.TrimEnd()
            if ($s.StartsWith('|')) { $s = $s.Substring(1) }
            if ($s.EndsWith('|'))   { $s = $s.Substring(0, $s.Length - 1) }
            $cells = @($s -split '\|' | ForEach-Object { $_.Trim() })

            if ($cells.Count -ge 10) {
                # Skip header rows and separator rows
                if ($cells[0] -match '^\*\*' -or $cells[0] -imatch '^Recommendation$' -or $cells[0] -match '^[\-:]+$') { continue }
                $recText       = $cells[0]
                $twodayId      = $cells[1]
                $cisRef        = $cells[2]
                # Use TwodayId as fallback identifier when CIS Reference is just a placeholder
                if ((-not $cisRef -or $cisRef -eq '-') -and $twodayId -and $twodayId -ne '-') {
                    $cisRef = $twodayId
                }
                $recProfile    = $cells[3]
                $cisSafeguard  = $cells[4]
                $type          = $cells[5]
                $origin        = $cells[6]
                $followed      = $cells[7]
                $notes         = $cells[8]
                $intunePolicy  = $cells[9]
                $references     = if ($cells.Count -ge 12) { $cells[11] } else { '-' }
                $gpSettingName  = if ($cells.Count -ge 13) { $cells[12] } else { '' }
                $remediationApp = if ($cells.Count -ge 14) { $cells[13] } else { '' }

                $settingName  = ''
                $settingValue = ''
                if ($recText -match "Ensure\s+'(.+)'\s+(?:is set to|Is|is)\s+'([^']+)'\s*$") {
                    $settingName  = $Matches[1]
                    $settingValue = $Matches[2]
                } elseif ($recText -match "Ensure\s+'(.+)'\s+(?:is set to|Is|is)\s+'([^']+)") {
                    $settingName  = $Matches[1]
                    $settingValue = $Matches[2]
                } elseif ($recText -match "Ensure\s+'(.+)'") {
                    $settingName = $Matches[1]
                }

                $recommendations += [PSCustomObject]@{
                    Recommendation = $recText
                    SettingName    = $settingName
                    SettingValue   = $settingValue
                    GpSettingName  = $gpSettingName
                    TwodayId       = $twodayId
                    CISReference   = $cisRef
                    Profile        = $recProfile
                    CISSafeguard   = $cisSafeguard
                    Type           = $type
                    Origin         = $origin
                    Followed       = $followed
                    Notes          = $notes
                    IntunePolicy   = $intunePolicy
                    Section        = $currentSection
                    SubSection     = $currentSubSection
                    References     = $references
                    RemediationApp = $remediationApp
                }
            }
        }
    }

    return $recommendations
}

function Connect-ToGraph {
    <#
    .SYNOPSIS
        Connects to Microsoft Graph with required scopes for Settings Catalog management.
    #>

    if (-not (Get-Module -ListAvailable -Name Microsoft.Graph.Authentication)) {
        Write-Error "Microsoft.Graph.Authentication module is required. Install it with:`nInstall-Module Microsoft.Graph.Authentication -Scope CurrentUser"
        return $false
    }

    Import-Module Microsoft.Graph.Authentication -ErrorAction Stop

    $scopes = @('DeviceManagementConfiguration.ReadWrite.All')

    try {
        $context = Get-MgContext
        if ($context) {
            $hasScopes = $true
            foreach ($s in $scopes) {
                if ($s -notin $context.Scopes) { $hasScopes = $false; break }
            }
            if ($hasScopes) {
                Write-Host "Already connected to Microsoft Graph as $($context.Account)" -ForegroundColor Green
                return $true
            }
        }

        Write-Host "Connecting to Microsoft Graph..." -ForegroundColor Cyan
        Connect-MgGraph -Scopes $scopes -ErrorAction Stop
        Write-Host "Connected to Microsoft Graph as $((Get-MgContext).Account)" -ForegroundColor Green
        return $true
    }
    catch {
        Write-Error "Failed to connect to Microsoft Graph: $($_.Exception.Message)"
        return $false
    }
}

function Get-SettingsCatalogTemplates {
    <#
    .SYNOPSIS
        Retrieves available Settings Catalog templates/categories for the platform.
    #>
    param([string]$Platform)

    $uri = "https://graph.microsoft.com/beta/deviceManagement/configurationPolicyTemplates?`$filter=platforms has '$Platform'"
    try {
        $response = Invoke-MgGraphRequest -Method GET -Uri $uri -ErrorAction Stop
        return $response.value
    }
    catch {
        Write-Warning "Could not retrieve policy templates: $($_.Exception.Message)"
        return @()
    }
}

function Search-SettingDefinition {
    <#
    .SYNOPSIS
        Searches the Settings Catalog for a setting by name.
        Tries multiple search strategies: display name variants, keyword search,
        and direct definition ID construction as last resort.
    #>
    param(
        [string]$SettingName,
        [string]$Platform,
        [string]$ProductIdPattern,
        [string]$CategoryHint
    )

    function Invoke-SettingSearch {
        param([string]$SearchTerm)
        $safeTerm = $SearchTerm -replace "'", "''"
        $searchUri = "https://graph.microsoft.com/beta/deviceManagement/configurationSettings?`$filter=contains(displayName,'$safeTerm')&`$top=25"
        try {
            $resp = Invoke-MgGraphRequest -Method GET -Uri $searchUri -ErrorAction Stop
            $hits = @($resp.value)
            if ($hits.Count -eq 0) { return @() }

            if ($Platform) {
                $compat = @($hits | Where-Object {
                    $app = $_.applicability
                    $pOk = if ($app -and $app.platform)       { $app.platform      -match $Platform } else { $true }
                    $tOk = if ($app -and $app.technologies)   { $app.technologies  -match '\bmdm\b' } else { $true }
                    $pOk -and $tOk
                })
                if ($compat.Count -gt 0) { $hits = $compat }
            }

            if ($ProductIdPattern -and $hits.Count -gt 0) {
                $prodHits = @($hits | Where-Object { $_.id -match $ProductIdPattern })
                if ($prodHits.Count -gt 0) { return $prodHits }

                # Fallback rule: if there is exactly one compatible catalog hit,
                # allow it even when it is outside the product-specific scope.
                if ($hits.Count -eq 1) {
                    $singleHit = $hits[0]
                    Write-Host "  Unique cross-product fallback: '$($singleHit.displayName)' (id: $($singleHit.id))" -ForegroundColor DarkCyan
                    return @($singleHit)
                }

                return @()
            }

            return $hits
        }
        catch {
            Write-Verbose "Search failed for '$SearchTerm': $($_.Exception.Message)"
            return @()
        }
    }

    # Strategy 1: Search by full display name
    $results = @(Invoke-SettingSearch -SearchTerm $SettingName)
    if ($results.Count -gt 0) { return $results }

    # Strategy 2: Strip common prefixes
    $prefix  = ''
    $stripped = $SettingName
    if ($SettingName -match '^(Enable|Disable|Configure|Allow|Block|Set|Specify)\s+(.+)$') {
        $prefix   = $Matches[1]
        $stripped = $Matches[2]
        $results  = @(Invoke-SettingSearch -SearchTerm $stripped)
        if ($results.Count -gt 0) {
            Write-Verbose "Found '$SettingName' using stripped search: '$stripped'"
            return $results
        }
    }

    # Strategy 3: Transform prefix to suffix
    if ($prefix) {
        $suffixMap = @{ 'Enable' = 'Enabled'; 'Disable' = 'Disabled'; 'Configure' = 'Configured';
                        'Allow'  = 'Allowed'; 'Block' = 'Blocked'; 'Set' = 'Set'; 'Specify' = 'Specified' }
        $suffix   = if ($suffixMap[$prefix]) { $suffixMap[$prefix] } else { "${prefix}d" }
        $suffixed = "$stripped $suffix"
        $results  = @(Invoke-SettingSearch -SearchTerm $suffixed)
        if ($results.Count -gt 0) {
            Write-Verbose "Found '$SettingName' using suffixed search: '$suffixed'"
            return $results
        }
    }

    # Strategy 4: Progressive substring — drop words from the left
    $words = ($stripped -split '\s+')
    if ($words.Count -ge 3) {
        for ($i = 1; $i -lt ($words.Count - 1); $i++) {
            $shorter = ($words[$i..($words.Count-1)]) -join ' '
            $results = @(Invoke-SettingSearch -SearchTerm $shorter)
            if ($results.Count -gt 0) {
                Write-Verbose "Found '$SettingName' using substring search: '$shorter'"
                return $results
            }
        }
    }

    # Strategy 5: Direct definition ID construction + fetch
    if ($CategoryHint) {
        $catLower  = $CategoryHint.ToLower()
        $nameWords = (($stripped -replace '[^a-zA-Z0-9\s]', '') -split '\s+') | ForEach-Object { $_.ToLower() }
        $cleanWords = @($nameWords | Where-Object { $_ -notin @('google','microsoft','edge','chrome','mozilla','firefox') })

        $keyVariations = @()
        $keyVariations += ($nameWords -join '')
        if ($cleanWords.Count -gt 0 -and ($cleanWords -join '') -ne ($nameWords -join '')) {
            $keyVariations += ($cleanWords -join '')
        }
        if ($prefix -eq 'Enable') {
            $keyVariations += ($cleanWords -join '') + 'enabled'
            $keyVariations += ($nameWords  -join '') + 'enabled'
        }
        elseif ($prefix -eq 'Disable') {
            $keyVariations += ($cleanWords -join '') + 'disabled'
        }

        $idPrefixes = @()
        switch ($ProductIdPattern) {
            'chrome'         { $idPrefixes += "device_vendor_msft_policy_config_chromeintunev1~policy~googlechrome~${catLower}_" }
            'microsoft_edge' { $idPrefixes += "device_vendor_msft_policy_config_microsoft_edgev116~policy~microsoft_edge~${catLower}_" }
            'firefox'        { $idPrefixes += "device_vendor_msft_policy_config_firefoxv126~policy~firefox~${catLower}_" }
        }

        foreach ($idPrefix in $idPrefixes) {
            foreach ($key in $keyVariations) {
                $candidateId = "${idPrefix}${key}"
                Write-Verbose "Trying direct ID: $candidateId"
                $directDef = Get-SettingDefinitionById -DefinitionId $candidateId
                if ($directDef) {
                    Write-Host "  Found via direct ID: $candidateId" -ForegroundColor DarkCyan
                    return @($directDef)
                }
            }
        }
    }

    # Strategy 6: Search by significant keywords
    $skipWords = @('the','for','and','all','set','with','from','that','this','not','are','use','has','its',
                   'can','how','new','per','google','microsoft','edge','chrome','mozilla','firefox')
    $keywords  = @(($SettingName -split '\s+') | Where-Object { $_.Length -ge 3 -and ($_.ToLower() -notin $skipWords) })
    if ($keywords.Count -ge 2) {
        $sortedKw = $keywords | Sort-Object { $_.Length } -Descending
        foreach ($kw in ($sortedKw | Select-Object -First 3)) {
            $results = @(Invoke-SettingSearch -SearchTerm $kw)
            if ($results.Count -gt 0 -and $results.Count -le 15) {
                Write-Verbose "Found '$SettingName' using keyword search: '$kw'"
                return $results
            }
        }
    }

    return @()
}

function Get-SettingDefinitionById {
    <#
    .SYNOPSIS
        Fetches a full setting definition by ID, including options/valueDefinition.
    #>
    param([string]$DefinitionId)

    $encodedId = [System.Uri]::EscapeDataString($DefinitionId)
    $uri = "https://graph.microsoft.com/beta/deviceManagement/configurationSettings('$encodedId')"
    try {
        $response = Invoke-MgGraphRequest -Method GET -Uri $uri -ErrorAction Stop
        return $response
    }
    catch {
        Write-Verbose "Could not fetch definition '$DefinitionId': $($_.Exception.Message)"
        return $null
    }
}

