#Requires -Version 5.1
<#
.SYNOPSIS
    Creates Intune Settings Catalog policies from a CIS Benchmark Markdown file.

.DESCRIPTION
    Run without arguments to open the graphical interface (WPF GUI).
    Pass -MdFilePath to run in headless / command-line mode (original
    New-IntuneCISPolicies.ps1 behaviour).

    The script:
    1. Reads the .md file and extracts all recommendation rows from the tables
    2. Groups settings by their Intune Policy name column
    3. For each unique policy name, creates a Settings Catalog configuration profile
       containing all the settings that belong to that group

    Settings are mapped to Settings Catalog definitions automatically; those that
    cannot be mapped are flagged for manual review.

    Requires the Microsoft.Graph.Authentication module and appropriate permissions.

.PARAMETER MdFilePath
    Path to the Markdown file generated by Convert-CISBenchmarkToMarkdown.ps1.
    Omit this parameter to launch the GUI.

.PARAMETER ProfileLevel
    Which CIS profile level to create policies for.
    - L1: Create policies only for L1 (Followed = Yes) recommendations
    - L2: Create policies for both L1 and L2 recommendations
    - All: Create policies for all recommendations regardless of profile
    Default: L1

.PARAMETER Platform
    The target platform for the policies. Default: windows10

.PARAMETER ProfileType
    Policy profile type to create.
    - SettingsCatalog: Create Settings Catalog policies (default)
    - Template: Create iOS device configuration template profiles (only supported for Platform iOS)

.PARAMETER PolicyFilter
    One or more policy names to process. All others are skipped.

.PARAMETER SettingFilter
    One or more CIS reference numbers to process. All others are skipped.

.PARAMETER RecommendationFilter
    One or more recommendation texts to process (fallback for items without CIS reference).

.PARAMETER ExportOnly
    Export parsed policy data to JSON instead of creating policies in Intune.

.PARAMETER UpdateExisting
    Replace the settings of existing policies that match by name.

.PARAMETER PreviewOnly
    Return the toolbox recommendation preview without opening a GUI or connecting to Graph.

.PARAMETER PreviewOrigin
    Filter the preview to All, CIS, or Twoday recommendations.

.PARAMETER WhatIf
    Show what would be created without making any changes.

.EXAMPLE
    # Open the GUI
    .\Invoke-IntuneCISPolicyCreator-GUI.ps1

.EXAMPLE
    # Headless: create L1 policies from a Chrome benchmark
    .\Invoke-IntuneCISPolicyCreator-GUI.ps1 -MdFilePath "C:\Benchmarks\Google Chrome.md"

.EXAMPLE
    # Headless: preview only (WhatIf)
    .\Invoke-IntuneCISPolicyCreator-GUI.ps1 -MdFilePath "C:\Benchmarks\Edge.md" -ProfileLevel L2 -WhatIf

.EXAMPLE
    # Headless: export JSON for review
    .\Invoke-IntuneCISPolicyCreator-GUI.ps1 -MdFilePath "C:\Benchmarks\Google Chrome.md" -ExportOnly
#>
[CmdletBinding(SupportsShouldProcess)]
param(
    [Parameter(Mandatory = $false)]
    [string]$MdFilePath = '',

    [Parameter(Mandatory = $false)]
    [ValidateSet('L1', 'L2', 'All')]
    [string]$ProfileLevel = 'L1',

    [Parameter(Mandatory = $false)]
    [string]$Platform = 'windows10',

    [Parameter(Mandatory = $false)]
    [ValidateSet('SettingsCatalog', 'Template')]
    [string]$ProfileType = 'SettingsCatalog',

    [Parameter(Mandatory = $false)]
    [string[]]$PolicyFilter,

    [Parameter(Mandatory = $false)]
    [string[]]$SettingFilter,

    [Parameter(Mandatory = $false)]
    [string[]]$RecommendationFilter,

    [Parameter(Mandatory = $false)]
    [switch]$ExportOnly,

    [Parameter(Mandatory = $false)]
    [switch]$UpdateExisting,

    [switch]$PreviewOnly,

    [ValidateSet('All','CIS','Twoday')]
    [string]$PreviewOrigin = 'All'
)

if ($PreviewOnly) {
    if (-not $MdFilePath -or -not (Test-Path -LiteralPath $MdFilePath -PathType Leaf)) { throw '-MdFilePath must name an existing Markdown file for -PreviewOnly.' }
    Import-Module (Join-Path (Split-Path $PSScriptRoot -Parent) 'Shared\BaselineToolkit.Common.psm1') -DisableNameChecking
    Get-BaselinePolicyPreview -MdFilePath $MdFilePath -ProfileLevel $ProfileLevel -OriginFilter $PreviewOrigin
    return
}

