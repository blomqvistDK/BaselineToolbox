        $platform           = ($cmbPlatform.SelectedItem).Tag
        $thisScript         = $script:thisScriptPath
        $expectedJsonPath   = [System.IO.Path]::ChangeExtension($mdPath, '.policies.json')

        $arguments = @(
            '-NoProfile', '-ExecutionPolicy', 'Bypass',
            '-File', $thisScript,
            '-MdFilePath', $mdPath,
            '-ProfileLevel', $profileLevel,
            '-Platform', $platform,
            '-ExportOnly',
            '-PolicyFilter',  ($selectedPolicies -join '|||'),
            '-SettingFilter', ($selectedRefs -join '|||')
        )
        if ($selectedRecTexts.Count -gt 0) {
            $arguments += '-RecommendationFilter'
            $arguments += ($selectedRecTexts -join '|||')
