        [System.IO.File]::WriteAllText($OutputPath, $html, [System.Text.UTF8Encoding]::new($false))
    }

    function Update-TenantInfo {
        try {
            $ctx = Get-MgContext -ErrorAction SilentlyContinue
            if ($ctx -and $ctx.TenantId) {
                $tenantDisplay = $ctx.TenantId
                if ($ctx.Account) { $tenantDisplay = "$($ctx.Account) ($($ctx.TenantId.Substring(0,8))...)" }
                $txtTenantInfo.Text       = $tenantDisplay
                $txtTenantInfo.Foreground = [System.Windows.Media.Brushes]::DarkGreen
                $btnGraphConnect.Content  = 'Sign Out'
            } else {
                $txtTenantInfo.Text       = 'Not connected'
                $txtTenantInfo.Foreground = [System.Windows.Media.Brushes]::Gray
                $btnGraphConnect.Content  = 'Sign In'
            }
        } catch {
            $txtTenantInfo.Text       = 'Not connected'
            $txtTenantInfo.Foreground = [System.Windows.Media.Brushes]::Gray
            $btnGraphConnect.Content  = 'Sign In'
        }
    }

