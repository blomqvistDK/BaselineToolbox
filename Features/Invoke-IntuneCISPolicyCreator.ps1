        $runspace.SessionStateProxy.SetVariable('manualItemsForReport',    $manualItems)
        $runspace.SessionStateProxy.SetVariable('mdPathForReport',         $mdPath)
        $runspace.SessionStateProxy.SetVariable('profileLevelForReport',   $profileLevel)
        $runspace.SessionStateProxy.SetVariable('platformForReport',       $platform)
        $runspace.SessionStateProxy.SetVariable('window',                  $window)
        $runspace.SessionStateProxy.SetVariable('buildHtmlReportSb',       (Get-Item Function:Build-HtmlReport).ScriptBlock)

        $ps = [powershell]::Create()
        $ps.Runspace = $runspace
        $ps.AddScript({
            function Write-Log {
                param([string]$Message)
                $txtLog.Dispatcher.Invoke([Action]{ $txtLog.AppendText("$Message`r`n"); $txtLog.ScrollToEnd() })
            }
            function Reset-Buttons {
                $btnExportOnly.Dispatcher.Invoke([Action]{
                    $btnExportOnly.IsEnabled     = $true
                    $btnCreatePolicies.IsEnabled = $true
                    $btnCreatePolicies.Content   = "$([char]::ConvertFromUtf32(0x1F680)) Create Policies"
                    $btnBrowseMd.IsEnabled       = $true
                })
