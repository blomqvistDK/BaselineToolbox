function Get-CategoryHintFromGpSettingName {
    <#
    .SYNOPSIS
        Derives a Settings Catalog category hint from GP Setting Name when available.
    #>
    param(
        [string]$GpSettingName,
        [string]$SettingName,
        [string]$FallbackHint
    )

    if ([string]::IsNullOrWhiteSpace($GpSettingName)) { return $FallbackHint }

    $gpRaw = $GpSettingName.Trim()
    if ($gpRaw -eq '-' -or $gpRaw -eq $SettingName) { return $FallbackHint }

    $genericSegments = @(
        'administrative templates',
        'computer configuration',
        'user configuration',
        'policies',
        'policy definitions',
        'classic administrative templates',
        'windows components',
        'microsoft office 2016'
    )

    $segments = @($gpRaw -split '[\\/|>]' | ForEach-Object { $_.Trim() } | Where-Object { $_ })
    if ($segments.Count -gt 0) {
        $filteredSegments = @($segments | Where-Object {
            $s = $_
            $sLower = $s.ToLower()
            ($s -ine $SettingName) -and ($genericSegments -notcontains $sLower)
        })

        if ($filteredSegments.Count -gt 0) {
            return $filteredSegments[-1]
        }
    }

    if ($gpRaw -match '^([^:]+):') {
        $prefix = $Matches[1].Trim()
        if ($prefix -and $prefix -ine $SettingName -and ($genericSegments -notcontains $prefix.ToLower())) {
            return $prefix
        }
    }

    return $FallbackHint
}

function Get-UsableGpSettingName {
    <#
    .SYNOPSIS
        Returns GP Setting Name only when it contains usable disambiguation data.
    #>
    param(
        [string]$GpSettingName,
        [string]$SettingName
    )

    if ([string]::IsNullOrWhiteSpace($GpSettingName)) { return '' }

    $gp = $GpSettingName.Trim()
    if ($gp -eq '-' -or $gp -ieq $SettingName) { return '' }

    return $gp
}

function Get-EventLogChannelTokens {
    <#
    .SYNOPSIS
        Derives Event Log channel ID tokens from GP/category/name text.
    #>
    param(
        [string]$SettingName,
        [string]$GpSettingName,
        [string]$CategoryHint,
        [string]$SubSection
    )

    $text = @($SettingName, $GpSettingName, $CategoryHint, $SubSection) -join ' '
    if ([string]::IsNullOrWhiteSpace($text)) { return @() }

    $tokens = [System.Collections.Generic.HashSet[string]]::new([System.StringComparer]::OrdinalIgnoreCase)

    if ($text -imatch '\bapplication\b') {
        [void]$tokens.Add('applicationlog')
        [void]$tokens.Add('application')
    }
    if ($text -imatch '\bsecurity\b') {
        [void]$tokens.Add('securitylog')
        [void]$tokens.Add('security')
    }
    if ($text -imatch '\bsystem\b') {
        [void]$tokens.Add('systemlog')
        [void]$tokens.Add('system')
    }
    if ($text -imatch '\bsetup\b') {
        [void]$tokens.Add('setuplog')
        [void]$tokens.Add('setup')
    }

    return @($tokens)
}

function Get-EventLogRetentionDefinitionId {
    <#
    .SYNOPSIS
        Forces ambiguous Event Log retention settings (.1 controls) to channel-specific definition IDs.
    #>
    param(
        [string]$SettingName,
        [string[]]$ChannelTokens,
        [object[]]$Definitions
    )

    if ([string]::IsNullOrWhiteSpace($SettingName)) { return '' }
    if ($SettingName -notlike 'Control Event Log behavior when the log file reaches its maximum size*') { return '' }
    if (-not $Definitions -or $Definitions.Count -eq 0) { return '' }

    $tokenPreference = @('application', 'security', 'setup', 'system')
    $selectedToken = $null

    foreach ($tok in $tokenPreference) {
        if ($ChannelTokens -contains $tok) {
            $selectedToken = $tok
            break
        }
    }

    if (-not $selectedToken) { return '' }

    $idPatterns = @(
        "*eventlogservice*${selectedToken}*retention*",
        "*eventlogservice*${selectedToken}log*retention*",
        "*admx_eventlog*${selectedToken}*retention*",
        "*admx_eventlog*${selectedToken}log*retention*",
        "*${selectedToken}*eventlog*retention*"
    )

    foreach ($pattern in $idPatterns) {
        $match = $Definitions | Where-Object { $_.id -and ([string]$_.id).ToLowerInvariant() -like $pattern } | Select-Object -First 1
        if ($match) { return [string]$match.id }
    }

    return ''
}

function Get-DefinitionMatchScore {
    <#
    .SYNOPSIS
        Scores definition candidates so ambiguous names prefer the right ID branch.
    #>
    param(
        [object]$Definition,
        [string]$SettingName,
        [string]$GpSettingName,
        [string[]]$ChannelTokens
    )

    $score = 0
    $displayName = ''
    $id = ''

    if ($Definition) {
        if ($Definition.displayName) { $displayName = [string]$Definition.displayName }
        if ($Definition.id) { $id = ([string]$Definition.id).ToLowerInvariant() }
    }

    if ($displayName -and $displayName -ieq $SettingName) { $score += 400 }
    if ($GpSettingName -and $GpSettingName -ne '-' -and $displayName -and $displayName -ieq $GpSettingName) { $score += 300 }

    if ($ChannelTokens -and $ChannelTokens.Count -gt 0) {
        foreach ($tok in $ChannelTokens) {
            if ($tok -and $id -like "*$($tok.ToLowerInvariant())*") { $score += 250 }
        }

        if ($id -like '*eventlogservice*' -or $id -like '*admx_eventlog*') {
            $score += 25
        }
    }

    return $score
}

function Build-SettingInstance {
    <#
    .SYNOPSIS
        Builds a properly formatted settingInstance object from a definition and recommended value.
    #>
    param(
        [object]$Definition,
        [string]$RecommendedValue,
        [string[]]$ExtraChildValues = @()
    )

    $defType = $Definition.'@odata.type'
    $defId   = $Definition.id

    switch -Wildcard ($defType) {
        '*ChoiceSettingCollectionDefinition' {
            $matchedOption = Find-MatchingOption -Options $Definition.options -Value $RecommendedValue
            if ($matchedOption) {
                return @{
                    '@odata.type'       = '#microsoft.graph.deviceManagementConfigurationChoiceSettingCollectionInstance'
                    settingDefinitionId = $defId
                    choiceSettingCollectionValue = @(
                        @{
                            '@odata.type' = '#microsoft.graph.deviceManagementConfigurationChoiceSettingValue'
                            value    = $matchedOption.itemId
                            children = @()
                        }
                    )
                }
            }
            return $null
        }
        '*ChoiceSettingDefinition' {
            $matchedOption = Find-MatchingOption -Options $Definition.options -Value $RecommendedValue
            if ($matchedOption) {
                $children            = @()
                $childValue          = $null
                $requiresChildValue  = $false

                if ($RecommendedValue -match '^(?:Enabled|Disabled):\s*(.+)$') {
                    $childValue         = $Matches[1].Trim()
                    $requiresChildValue = $true
                }

                if ($matchedOption.dependedOnBy -and @($matchedOption.dependedOnBy).Count -gt 0) {
                    $requiredChildCount = 0
                    foreach ($dep in @($matchedOption.dependedOnBy)) {
                        $childDefId = $dep.dependedOnBy
                        if (-not $childDefId) { continue }
                        $requiredChildCount++

                        $childDef = Get-SettingDefinitionById -DefinitionId $childDefId
                        if (-not $childDef) { continue }

                        # Try primary child value first
                        $childInstance = Build-ChildSettingInstance -ChildDefinition $childDef -Value $childValue

                        # If primary fails, try each sibling rec value (e.g. 'Unchecked: Do not allow edit'
                        # from a companion CIS rec that maps to the same parent setting)
                        if (-not $childInstance -and $ExtraChildValues.Count -gt 0) {
                            foreach ($extraVal in $ExtraChildValues) {
                                $childInstance = Build-ChildSettingInstance -ChildDefinition $childDef -Value $extraVal
                                if (-not $childInstance -and $extraVal -imatch '^(?:Checked|Unchecked|Enabled|Disabled)\s*:\s*(.+)$') {
                                    $childInstance = Build-ChildSettingInstance -ChildDefinition $childDef -Value $Matches[1].Trim()
                                }
                                if ($childInstance) { break }
                            }
                        }

                        if ($childInstance) { $children += $childInstance }
                    }

                    if ($requiresChildValue -and $requiredChildCount -gt 0 -and $children.Count -eq 0) {
                        return $null
                    }
                }
                elseif ($childValue) {
                    $parentKey  = ($defId -split '~')[-1]
                    $settingKey = ($parentKey -split '_')[-1]

                    $childDef   = $null
                    $childDefId = "${defId}_${settingKey}desc"
                    $childDef   = Get-SettingDefinitionById -DefinitionId $childDefId

                    if (-not $childDef) {
                        $childDefId = "${defId}_${settingKey}"
                        $childDef   = Get-SettingDefinitionById -DefinitionId $childDefId
                    }

                    if ($childDef) {
                        $childInstance = Build-ChildSettingInstance -ChildDefinition $childDef -Value $childValue
                        if ($childInstance) {
                            $children += $childInstance
                        } else {
                            return $null
                        }
                    }
                }

                return @{
                    '@odata.type'       = '#microsoft.graph.deviceManagementConfigurationChoiceSettingInstance'
                    settingDefinitionId = $defId
                    choiceSettingValue  = @{
                        '@odata.type' = '#microsoft.graph.deviceManagementConfigurationChoiceSettingValue'
                        value    = $matchedOption.itemId
                        children = $children
                    }
                }
            }
            return $null
        }
        '*SimpleSettingCollectionDefinition' {
            $values = @($RecommendedValue -split ',' | ForEach-Object { $_.Trim() } | Where-Object { $_ })
            if ($values.Count -eq 0) { $values = @($RecommendedValue) }
            return @{
                '@odata.type'       = '#microsoft.graph.deviceManagementConfigurationSimpleSettingCollectionInstance'
                settingDefinitionId = $defId
                simpleSettingCollectionValue = @($values | ForEach-Object {
                    @{
                        '@odata.type' = '#microsoft.graph.deviceManagementConfigurationStringSettingValue'
                        value = $_
                    }
                })
            }
        }
        '*SimpleSettingDefinition' {
            $valueDefType = $Definition.valueDefinition.'@odata.type'
            if ($valueDefType -like '*Integer*') {
                $intValue = 0
                if ($RecommendedValue -match '(\d+)') { $intValue = [int64]$Matches[1] }
                return @{
                    '@odata.type'       = '#microsoft.graph.deviceManagementConfigurationSimpleSettingInstance'
                    settingDefinitionId = $defId
                    simpleSettingValue  = @{
                        '@odata.type' = '#microsoft.graph.deviceManagementConfigurationIntegerSettingValue'
                        value = $intValue
                    }
                }
            }
            else {
                return @{
                    '@odata.type'       = '#microsoft.graph.deviceManagementConfigurationSimpleSettingInstance'
                    settingDefinitionId = $defId
                    simpleSettingValue  = @{
                        '@odata.type' = '#microsoft.graph.deviceManagementConfigurationStringSettingValue'
                        value = $RecommendedValue
                    }
                }
            }
        }
        default {
            Write-Verbose "Unsupported definition type: $defType"
            return $null
        }
    }
}

function Build-ChildSettingInstance {
    <#
    .SYNOPSIS
        Builds a child setting instance for a dependent setting within a choice setting.
    #>
    param(
        [object]$ChildDefinition,
        [string]$Value
    )

    $childType = $ChildDefinition.'@odata.type'
    $childId   = $ChildDefinition.id

    switch -Wildcard ($childType) {
        '*SimpleSettingCollectionDefinition' {
            $values = @($Value -split ',' | ForEach-Object { $_.Trim() } | Where-Object { $_ })
            if ($values.Count -eq 0) { $values = @($Value) }
            return @{
                '@odata.type'       = '#microsoft.graph.deviceManagementConfigurationSimpleSettingCollectionInstance'
                settingDefinitionId = $childId
                simpleSettingCollectionValue = @($values | ForEach-Object {
                    @{
                        '@odata.type' = '#microsoft.graph.deviceManagementConfigurationStringSettingValue'
                        value = $_
                    }
                })
            }
        }
        '*SimpleSettingDefinition' {
            $valueDefType = $ChildDefinition.valueDefinition.'@odata.type'
            if ($valueDefType -like '*Integer*') {
                $intVal = 0
                if ($Value -match '(\d+)') { $intVal = [int64]$Matches[1] }
                return @{
                    '@odata.type'       = '#microsoft.graph.deviceManagementConfigurationSimpleSettingInstance'
                    settingDefinitionId = $childId
                    simpleSettingValue  = @{
                        '@odata.type' = '#microsoft.graph.deviceManagementConfigurationIntegerSettingValue'
                        value = $intVal
                    }
                }
            }
            else {
                return @{
                    '@odata.type'       = '#microsoft.graph.deviceManagementConfigurationSimpleSettingInstance'
                    settingDefinitionId = $childId
                    simpleSettingValue  = @{
                        '@odata.type' = '#microsoft.graph.deviceManagementConfigurationStringSettingValue'
                        value = $Value
                    }
                }
            }
        }
        '*ChoiceSettingDefinition' {
            $matched = Find-MatchingOption -Options $ChildDefinition.options -Value $Value
            if ($matched) {
                return @{
                    '@odata.type'       = '#microsoft.graph.deviceManagementConfigurationChoiceSettingInstance'
                    settingDefinitionId = $childId
                    choiceSettingValue  = @{
                        '@odata.type' = '#microsoft.graph.deviceManagementConfigurationChoiceSettingValue'
                        value    = $matched.itemId
                        children = @()
                    }
                }
            }
            return $null
        }
        default {
            Write-Verbose "Unsupported child definition type: $childType for $childId"
            return $null
        }
    }
}

function Find-MatchingOption {
    <#
    .SYNOPSIS
        Matches a CIS recommended value to a choice setting option.
    #>
    param(
        [array]$Options,
        [string]$Value
    )

    if (-not $Options -or $Options.Count -eq 0) { return $null }

    $embeddedNum = $null
    if ($Value -match '\((\d+)\)\s*$') { $embeddedNum = $Matches[1] }

    if ($embeddedNum) {
        $match = $Options | Where-Object { $_.itemId -like "*_$embeddedNum" } | Select-Object -First 1
        if ($match) { return $match }
    }

    $candidates   = @($Value)
    $valueNoNum   = $Value -replace '\s*\(\d+\)\s*$', ''
    if ($valueNoNum -ne $Value) { $candidates += $valueNoNum }

    $strippedValue = $null
    if ($Value -imatch '^(Enabled|Disabled)\s*:\s*(.+)$') {
        $prefixKeyword = $Matches[1]
        $strippedValue = $Matches[2].Trim()
        $candidates   += $prefixKeyword
        $candidates   += $strippedValue
        $strippedNoNum = $strippedValue -replace '\s*\(\d+\)\s*$', ''
        if ($strippedNoNum -ne $strippedValue) { $candidates += $strippedNoNum }
    }
    # Handle Checked/Unchecked (used for checkbox child settings in Office policies)
    if ($Value -imatch '^(Checked|Unchecked)\s*(?::\s*(.+))?$') {
        $checkKeyword = $Matches[1]
        $candidates  += $checkKeyword
        if ($Matches[2]) { $candidates += $Matches[2].Trim() }
    }

    foreach ($candidate in $candidates) {
        $match = $Options | Where-Object { $_.displayName -eq  $candidate } | Select-Object -First 1
        if ($match) { return $match }
        $match = $Options | Where-Object { $_.displayName -ieq $candidate } | Select-Object -First 1
        if ($match) { return $match }
    }

    foreach ($candidate in $candidates) {
        if ($candidate -match '^\d+$') {
            $match = $Options | Where-Object { $_.itemId -like "*_$candidate" } | Select-Object -First 1
            if ($match) { return $match }
        }
        $match = $Options | Where-Object { $_.displayName -like "*$candidate*" } | Select-Object -First 1
        if ($match) { return $match }
        $match = $Options | Where-Object { $candidate -like "*$($_.displayName)*" } | Select-Object -First 1
        if ($match) { return $match }
    }

    if ($Value -imatch '^enabled$' -or ($Value -imatch '^enabled\s*:' -and -not $strippedValue)) {
        $match = $Options | Where-Object { $_.displayName -imatch 'enabled' -or $_.itemId -like '*_1' } | Select-Object -First 1
        if ($match) { return $match }
    }
    if ($Value -imatch '^disabled$' -or ($Value -imatch '^disabled\s*:' -and -not $strippedValue)) {
        $match = $Options | Where-Object { $_.displayName -imatch 'disabled' -or $_.itemId -like '*_0' } | Select-Object -First 1
        if ($match) { return $match }
    }
    # Checked = true/1, Unchecked = false/0 — used for checkbox child settings
    if ($Value -imatch '^checked$' -or $Value -imatch '^checked\s*:') {
        $match = $Options | Where-Object { $_.itemId -like '*_1' -or $_.displayName -imatch '\bchecked\b' } | Select-Object -First 1
        if ($match) { return $match }
    }
    if ($Value -imatch '^unchecked$' -or $Value -imatch '^unchecked\s*:') {
        $match = $Options | Where-Object { $_.itemId -like '*_0' -or $_.displayName -imatch '\bunchecked\b' } | Select-Object -First 1
        if ($match) { return $match }
    }

    return $null
}

