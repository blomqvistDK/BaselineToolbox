# ══════════════════════════════════════════════════════════════════════════════
#  ENTRY POINT  —  CLI mode when -MdFilePath is supplied, otherwise GUI mode
# ══════════════════════════════════════════════════════════════════════════════

if ($MdFilePath) {

    # ══════════════════════════════════════════════════════════════════════════
    #  CLI / Headless Mode
    # ══════════════════════════════════════════════════════════════════════════

    if (-not (Test-Path $MdFilePath -PathType Leaf)) {
        Write-Error "File not found: $MdFilePath"
        exit 1
    }

    Write-Host ""
    Write-Host "============================================" -ForegroundColor Cyan
    Write-Host "  CIS Benchmark -> Intune Policy Creator" -ForegroundColor Cyan
    Write-Host "============================================" -ForegroundColor Cyan
    Write-Host ""

    # Step 1: Parse the MD file
    Write-Host "Parsing MD file: $MdFilePath" -ForegroundColor Cyan
    $allRecs = Parse-MdFile -Path $MdFilePath

    if ($allRecs.Count -eq 0) {
        Write-Error "No recommendations found in the MD file."
        exit 1
    }

    Write-Host "Found $($allRecs.Count) total recommendations" -ForegroundColor Green

    # Detect product from filename to filter setting definitions by product
    $mdFileName = (Split-Path $MdFilePath -Leaf) -replace '\.md$', ''
    $ProductIdPattern = switch -Wildcard ($mdFileName) {
        '*Chrome*'  { 'chrome'; break }
        '*Edge*'    { 'microsoft_edge'; break }
        '*Firefox*' { 'firefox'; break }
        '*Windows*' { $null; break }
        default     { $null }
    }
    if ($ProductIdPattern) {
        Write-Host "Product detected: $mdFileName (setting ID filter: *$ProductIdPattern*)" -ForegroundColor Green
    } else {
        Write-Host "Product detected: $mdFileName (no product-specific ID filter)" -ForegroundColor Green
    }

    # Step 2: Filter by profile level
    $filteredRecs = @(switch ($ProfileLevel) {
        'L1'  { $allRecs | Where-Object { $_.Followed -eq 'Yes' -or $_.Origin -imatch 'twoday' } }
        'L2'  { $allRecs }
        'All' { $allRecs }
    })

    $isIosTemplateMode = ($Platform -eq 'iOS' -and $ProfileType -eq 'Template')
    if ($ProfileType -eq 'Template' -and -not $isIosTemplateMode) {
        Write-Error "ProfileType 'Template' is only supported when Platform is 'iOS'."
        exit 1
    }

    Write-Host "After filtering ($ProfileLevel): $($filteredRecs.Count) recommendations" -ForegroundColor Green
    Write-Host "Profile type: $ProfileType" -ForegroundColor Green

    # Step 3: Group by Intune Policy name
    $policyGroups = $filteredRecs | Group-Object -Property IntunePolicy | Sort-Object Name

    # Step 3b: Apply policy name filter if specified
    if ($PolicyFilter -and $PolicyFilter.Count -gt 0) {
        $resolvedFilter = @()
        foreach ($pf in $PolicyFilter) { $resolvedFilter += $pf -split '\|\|\|' }
        $resolvedFilter = @($resolvedFilter | Where-Object { $_.Trim() } | ForEach-Object { $_.Trim() })
        $allGroupCount  = ($policyGroups | Measure-Object).Count
        $policyGroups   = @($policyGroups | Where-Object { $_.Name -in $resolvedFilter })
        Write-Host "Policy filter applied: $($policyGroups.Count) of $allGroupCount policies selected" -ForegroundColor Yellow
    }

    # Step 3c: Apply individual setting (CIS ref) filter if specified
    $resolvedSettingFilter = $null
    if ($SettingFilter -and $SettingFilter.Count -gt 0) {
        $resolvedSettingFilter = @()
        foreach ($sf in $SettingFilter) { $resolvedSettingFilter += $sf -split '\|\|\|' }
        $resolvedSettingFilter = @($resolvedSettingFilter | Where-Object { $_.Trim() } | ForEach-Object { $_.Trim() })
        Write-Host "Setting filter: $($resolvedSettingFilter.Count) individual settings selected" -ForegroundColor Yellow
    }

    # Step 3d: Apply recommendation text filter (fallback for items without CIS ref)
    $resolvedRecFilter = $null
    if ($RecommendationFilter -and $RecommendationFilter.Count -gt 0) {
        $resolvedRecFilter = @()
        foreach ($rf in $RecommendationFilter) { $resolvedRecFilter += $rf -split '\|\|\|' }
        $resolvedRecFilter = @($resolvedRecFilter | Where-Object { $_.Trim() } | ForEach-Object { $_.Trim() })
        Write-Host "Recommendation filter: $($resolvedRecFilter.Count) items by name" -ForegroundColor Yellow
    }

    Write-Host "Policies to create: $($policyGroups.Count)" -ForegroundColor Green
    Write-Host ""

    # Display summary
    Write-Host "Policy Summary:" -ForegroundColor Cyan
    Write-Host ("-" * 80)
    foreach ($group in $policyGroups) {
        $summaryRecs = @($group.Group)
        if ($resolvedSettingFilter -or $resolvedRecFilter) {
            $summaryRecs = @($summaryRecs | Where-Object {
                ($resolvedSettingFilter -and $_.CISReference -in $resolvedSettingFilter) -or
                ($resolvedRecFilter -and $_.Recommendation -in $resolvedRecFilter)
            })
        }
        if ($summaryRecs.Count -eq 0) { continue }
        $l1Count = @($summaryRecs | Where-Object { $_.Profile -eq 'L1' }).Count
        $l2Count = @($summaryRecs | Where-Object { $_.Profile -eq 'L2' }).Count
        Write-Host ("  {0,-60} L1:{1} L2:{2}" -f $group.Name, $l1Count, $l2Count)
    }
    Write-Host ("-" * 80)
    Write-Host ""

    # Step 4: Build policy data structure
    $policyData = @()

    foreach ($group in $policyGroups) {
        $groupRecs = @($group.Group)
        if ($resolvedSettingFilter -or $resolvedRecFilter) {
            $groupRecs = @($groupRecs | Where-Object {
                ($resolvedSettingFilter -and $_.CISReference -in $resolvedSettingFilter) -or
                ($resolvedRecFilter -and $_.Recommendation -in $resolvedRecFilter)
            })
            if ($groupRecs.Count -eq 0) { continue }
        }
        $settings = @()
        foreach ($rec in $groupRecs) {
            $settings += [PSCustomObject]@{
                SettingName    = $rec.SettingName
                GpSettingName  = $rec.GpSettingName
                SettingValue   = $rec.SettingValue
                CISReference   = $rec.CISReference
                Profile        = $rec.Profile
                Recommendation = $rec.Recommendation
                Type           = $rec.Type
                Section        = $rec.Section
                SubSection     = $rec.SubSection
                RemediationApp = $rec.RemediationApp
            }
        }

        $cisRefs     = ($groupRecs | ForEach-Object { $_.CISReference }) -join ', '
        $description = "CIS Benchmark settings: $cisRefs. Created from $(Split-Path $MdFilePath -Leaf). Profile: $ProfileLevel."

        $policyData += [PSCustomObject]@{
            PolicyName   = $group.Name
            Description  = $description
            Settings     = $settings
            SettingCount = $settings.Count
        }
    }

    # Step 5: Export or Create
    if ($ExportOnly) {
        $exportPath = [System.IO.Path]::ChangeExtension($MdFilePath, '.policies.json')

        $exportData = $policyData | ForEach-Object {
            $entry = [ordered]@{
                PolicyName   = $_.PolicyName
                Description  = $_.Description
                ProfileType  = $ProfileType
                SettingCount = $_.SettingCount
                Settings     = @($_.Settings | ForEach-Object {
                    @{
                        SettingName    = $_.SettingName
                        SettingValue   = $_.SettingValue
                        CISReference   = $_.CISReference
                        Profile        = $_.Profile
                        Recommendation = $_.Recommendation
                        Type           = $_.Type
                    }
                })
            }

            if ($isIosTemplateMode) {
                $templateProjection = Get-IosTemplateFieldUpdatesFromSettings -Settings $_.Settings
                if ($templateProjection.Updates.Count -gt 0) {
                    $entry.TemplateProperties = [ordered]@{}
                    foreach ($k in ($templateProjection.Updates.Keys | Sort-Object)) {
                        $entry.TemplateProperties[$k] = $templateProjection.Updates[$k]
                    }
                }
            }

            $entry
        }

        $exportData | ConvertTo-Json -Depth 10 | Set-Content -Path $exportPath -Encoding UTF8
        Write-Host "Exported policy data to: $exportPath" -ForegroundColor Green
        Write-Host ""

        Write-Host "Settings per policy:" -ForegroundColor Cyan
        foreach ($policy in $policyData) {
            Write-Host ""
            Write-Host "  Policy: $($policy.PolicyName)" -ForegroundColor Yellow
            Write-Host "  Description: $($policy.Description)" -ForegroundColor DarkGray
            foreach ($s in $policy.Settings) {
                $valueDisplay = if ($s.SettingValue) { " -> '$($s.SettingValue)'" } else { '' }
                Write-Host ("    [{0}] {1}{2}" -f $s.CISReference, $s.SettingName, $valueDisplay)
            }
        }

        Write-Host ""
        Write-Host "Review the JSON file, then run without -ExportOnly to create the policies." -ForegroundColor Yellow
        exit 0
    }

    # Connect to Graph
    $connected = Connect-ToGraph
    if (-not $connected) {
        Write-Error "Cannot proceed without Microsoft Graph connection."
        exit 1
    }

    # Load all existing policies once
    Write-Host "Loading existing policies from Intune..." -ForegroundColor Cyan
    if ($isIosTemplateMode) {
        $allExistingPolicies = Get-AllIosGeneralDeviceConfigurations
        Write-Host "Found $($allExistingPolicies.Count) existing iOS template policies in Intune" -ForegroundColor $(if ($allExistingPolicies.Count -gt 0) { 'Yellow' } else { 'Gray' })
    } else {
        $allExistingPolicies = Get-AllConfigurationPolicies
        Write-Host "Found $($allExistingPolicies.Count) existing Settings Catalog policies in Intune" -ForegroundColor $(if ($allExistingPolicies.Count -gt 0) { 'Yellow' } else { 'Gray' })
    }

    # Create / Update policies
    $created         = 0
    $updated         = 0
    $skipped         = 0
    $failed          = 0
    $failedPolicies  = @()
    $notFoundInIntune = @()

    foreach ($policy in $policyData) {
        Write-Host ""

        $existingPolicyObj = $null
        $policyExists      = $allExistingPolicies.TryGetValue($policy.PolicyName, [ref]$existingPolicyObj)

        if ($policyExists -and -not $UpdateExisting) {
            Write-Host "SKIP: '$($policy.PolicyName)' already exists" -ForegroundColor Yellow
            $skipped++
            continue
        }

        $actionLabel = if ($policyExists) { 'Updating' } else { 'Creating' }
        Write-Host "${actionLabel}: $($policy.PolicyName) ($($policy.SettingCount) settings)" -ForegroundColor Cyan

        if ($isIosTemplateMode) {
            $templateProjection = Get-IosTemplateFieldUpdatesFromSettings -Settings $policy.Settings
            $templateUpdates = $templateProjection.Updates
            $templateUnmapped = @($templateProjection.Unmapped)

            if ($templateUpdates.Count -eq 0) {
                Write-Host "  SKIPPED: '$($policy.PolicyName)' - no settings could be mapped to iOS template fields" -ForegroundColor Yellow
                $failed++
                $failedPolicies += $policy.PolicyName
                continue
            }

            Write-Host "  iOS template field updates: $($templateUpdates.Count)" -ForegroundColor DarkGray

            if ($templateUnmapped.Count -gt 0) {
                Write-Host "  Warning: $($templateUnmapped.Count) setting(s) could not be mapped to iOS template properties" -ForegroundColor Yellow
                Write-Host "  These settings need manual configuration after policy creation" -ForegroundColor Yellow
            }

            $description = $policy.Description
            if ($templateUnmapped.Count -gt 0) {
                $unmappedRefs = ($templateUnmapped | ForEach-Object { $_.CISReference } | Where-Object { $_ } | Select-Object -Unique) -join ', '
                if ($unmappedRefs) {
                    $description += " | Manual config needed for: $unmappedRefs"
                }
            }

            $actionWord = if ($policyExists) { 'Update iOS template policy' } else { 'Create iOS template policy' }
            if ($PSCmdlet.ShouldProcess($policy.PolicyName, $actionWord)) {
                if ($policyExists) {
                    $existingId = $existingPolicyObj.id
                    $success = Update-IosTemplatePolicy -PolicyId $existingId -PolicyName $policy.PolicyName -Description $description -TemplateUpdates $templateUpdates
                    if ($success) {
                        Write-Host "  UPDATED: $($policy.PolicyName) (ID: $existingId)" -ForegroundColor Green
                        $updated++
                    } else {
                        Write-Host "  FAILED: $($policy.PolicyName)" -ForegroundColor Red
                        $failed++
                        $failedPolicies += $policy.PolicyName
                    }
                }
                else {
                    $result = New-IosTemplatePolicy -PolicyName $policy.PolicyName -Description $description -TemplateUpdates $templateUpdates
                    if ($result) {
                        Write-Host "  CREATED: $($policy.PolicyName) (ID: $($result.id))" -ForegroundColor Green
                        $created++
                    } else {
                        Write-Host "  FAILED: $($policy.PolicyName)" -ForegroundColor Red
                        $failed++
                        $failedPolicies += $policy.PolicyName
                    }
                }
            }

            continue
        }

        $graphSettings    = @()
        $graphSettingsByDefinitionId = @{}
        $unmappedSettings = @()
        # Track setting names already mapped to avoid creating duplicate Graph settings
        # for sibling CIS recs that map to the same Intune setting (e.g. .4 and .5 for
        # 'Set document behavior if file validation fails').
        $processedSettingNames = [System.Collections.Generic.HashSet[string]]::new(
            [System.StringComparer]::OrdinalIgnoreCase)

        $policyCategoryHint = ($policy.PolicyName -split '-')[-1]

        foreach ($setting in $policy.Settings) {
            if (-not $setting.SettingName) {
                $unmappedSettings += $setting
                continue
            }

            # Determine per-setting product ID pattern: for M365Apps files each section
            # belongs to a specific app (Excel, Word, PowerPoint…) so we can narrow
            # the Settings Catalog search to the right app-scoped definitions.
            # NOTE: must be computed before the dedup check so the key includes the app.
            $effectiveProductIdPattern = $ProductIdPattern
            # Prefer RemediationApp (stored from PDF Remediation path first segment, e.g. "Microsoft Excel 2016")
            # over Section (from markdown heading). Section is unreliable because deep sub-headings
            # like "2.2.4 Excel Options" overwrite the app-level "2.2 Microsoft Excel 2016" heading.
            $appSource = if ($setting.RemediationApp -and $setting.RemediationApp -ne '-') {
                $setting.RemediationApp
            } else {
                $setting.Section
            }
            if ($appSource) {
                $appPattern = Get-AppProductIdPattern -Section $appSource
                if ($appPattern) { $effectiveProductIdPattern = $appPattern }
            }

            $usableGpSettingName = Get-UsableGpSettingName -GpSettingName $setting.GpSettingName -SettingName $setting.SettingName
            $categoryHint = Get-CategoryHintFromGpSettingName -GpSettingName $setting.GpSettingName -SettingName $setting.SettingName -FallbackHint $policyCategoryHint

            if ($categoryHint -ne $policyCategoryHint) {
                Write-Verbose "Using GP-derived category hint '$categoryHint' for '$($setting.SettingName)'"
            }

            $gpDedupToken = if ($usableGpSettingName) { $usableGpSettingName.ToLowerInvariant() } else { '' }

            # Dedup key combines setting name AND app pattern so that the same setting
            # name in different apps (Excel/PowerPoint/Word) each get their own entry.
            # Include category, GP token, and SubSection so similarly named settings in
            # different categories or subsections (e.g. Event Log channels) are not
            # incorrectly merged.
            $settingDedupKey = "$($setting.SettingName)|$effectiveProductIdPattern|$categoryHint|$gpDedupToken|$($setting.SubSection)"

            # Skip sibling recs whose parent name+app was already successfully processed
            if ($processedSettingNames.Contains($settingDedupKey)) {
                Write-Host "  Merged sibling: CIS $($setting.CISReference) '$($setting.SettingValue)' folded into parent setting '$($setting.SettingName)'" -ForegroundColor DarkGray
                continue
            }

            # Collect values from other recs in this policy that share the same SettingName,
            # app context and category context (siblings = additional child values for the same app,
            # e.g. the 'Unchecked' checkbox rec alongside the 'Enabled:...' parent rec).
            $siblingValues = @($policy.Settings |
                Where-Object {
                    $candidateUsableGp = Get-UsableGpSettingName -GpSettingName $_.GpSettingName -SettingName $_.SettingName
                    $candidateCategoryHint = Get-CategoryHintFromGpSettingName -GpSettingName $_.GpSettingName -SettingName $_.SettingName -FallbackHint $policyCategoryHint

                    $_.SettingName  -eq $setting.SettingName -and
                    $_.CISReference -ne $setting.CISReference -and
                    $_.Section      -eq $setting.Section -and
                    $_.SubSection   -eq $setting.SubSection -and
                    $candidateCategoryHint -eq $categoryHint -and
                    $candidateUsableGp -eq $usableGpSettingName
                } |
                ForEach-Object { $_.SettingValue })

            $definitions  = Search-SettingDefinition -SettingName $setting.SettingName -Platform $Platform -ProductIdPattern $effectiveProductIdPattern -CategoryHint $categoryHint
            if ($definitions.Count -eq 0 -and $categoryHint -ne $policyCategoryHint) {
                $definitions = Search-SettingDefinition -SettingName $setting.SettingName -Platform $Platform -ProductIdPattern $effectiveProductIdPattern -CategoryHint $policyCategoryHint
            }

            if ($definitions.Count -gt 0) {
                $definitions = @($definitions | Where-Object {
                    Test-NameSimilarity -CISName $setting.SettingName -CatalogName $_.displayName
                })
            }

            if ($definitions.Count -eq 0 -and $setting.GpSettingName -and $setting.GpSettingName -ne '-' -and
                $setting.GpSettingName -ne $setting.SettingName) {
                Write-Verbose "Retrying search using GP path setting name: '$($setting.GpSettingName)'"
                $gpDefinitions = Search-SettingDefinition -SettingName $setting.GpSettingName -Platform $Platform -ProductIdPattern $effectiveProductIdPattern -CategoryHint $categoryHint
                if ($gpDefinitions.Count -eq 0 -and $categoryHint -ne $policyCategoryHint) {
                    $gpDefinitions = Search-SettingDefinition -SettingName $setting.GpSettingName -Platform $Platform -ProductIdPattern $effectiveProductIdPattern -CategoryHint $policyCategoryHint
                }
                if ($gpDefinitions.Count -gt 0) {
                    $gpDefinitions = @($gpDefinitions | Where-Object {
                        Test-NameSimilarity -CISName $setting.GpSettingName -CatalogName $_.displayName
                    })
                }
                if ($gpDefinitions.Count -gt 0) {
                    Write-Host "  GP Path retry succeeded for '$($setting.SettingName)' using '$($setting.GpSettingName)'" -ForegroundColor DarkCyan
                    $definitions = $gpDefinitions
                }
            }

            if ($definitions.Count -gt 0) {
                $channelTokens = Get-EventLogChannelTokens -SettingName $setting.SettingName -GpSettingName $setting.GpSettingName -CategoryHint $categoryHint -SubSection $setting.SubSection
                $sortProperties = @(
                    @{ Expression = { Get-DefinitionMatchScore -Definition $_ -SettingName $setting.SettingName -GpSettingName $setting.GpSettingName -ChannelTokens $channelTokens }; Descending = $true },
                    @{ Expression = { if ($_.displayName) { [string]$_.displayName } else { '' } }; Descending = $false },
                    @{ Expression = { if ($_.id) { [string]$_.id } else { '' } }; Descending = $false }
                )
                $orderedDefinitions = @($definitions | Sort-Object -Property $sortProperties)

                $forcedEventLogRetentionId = Get-EventLogRetentionDefinitionId -SettingName $setting.SettingName -ChannelTokens $channelTokens -Definitions $orderedDefinitions
                if ($forcedEventLogRetentionId) {
                    $orderedDefinitions = @($orderedDefinitions | Where-Object { $_.id -eq $forcedEventLogRetentionId })
                    Write-Verbose "Forced Event Log retention mapping for '$($setting.SettingName)' to '$forcedEventLogRetentionId'"
                }

                $selectedMatch                 = $null
                $settingInstanceObj            = $null
                $foundDefButNeedsCustomerInfo  = $false

                foreach ($candidate in $orderedDefinitions) {
                    $fullDef = Get-SettingDefinitionById -DefinitionId $candidate.id
                    if (-not $fullDef) { $fullDef = $candidate }

                    $candidateInstance = Build-SettingInstance -Definition $fullDef -RecommendedValue $setting.SettingValue -ExtraChildValues $siblingValues

                    if (-not $candidateInstance) {
                        $defType            = $fullDef.'@odata.type'
                        $isListType         = $defType -like '*SimpleSettingCollectionDefinition' -or $defType -like '*ChoiceSettingDefinition'
                        $valueNeedsCustomer = ($setting.SettingValue -match '<|>|\[URL\]|\[Sites?\]|Enabled:\s*$' -or
                                              $setting.SettingValue -eq 'Enabled' -and $isListType)
                        if (-not $valueNeedsCustomer -and $defType -like '*ChoiceSettingDefinition') {
                            $matchedOpt = $null
                            if ($fullDef.options) {
                                $matchedOpt = $fullDef.options | Where-Object {
                                    $_.displayName -ieq 'Enabled' -or $_.itemId -like '*_1'
                                } | Select-Object -First 1
                            }
                            if ($matchedOpt -and $matchedOpt.dependedOnBy) {
                                foreach ($dep in $matchedOpt.dependedOnBy) {
                                    $childId = $dep.dependedOnBy
                                    if ($childId) {
                                        $childDef = Get-SettingDefinitionById -DefinitionId $childId
                                        if ($childDef -and $childDef.'@odata.type' -like '*SimpleSettingCollectionDefinition') {
                                            $valueNeedsCustomer = $true
                                            break
                                        }
                                    }
                                }
                            }
                        }
                        if ($valueNeedsCustomer) {
                            $foundDefButNeedsCustomerInfo = $true
                            $selectedMatch = $candidate
                        }
                    }

                    if ($candidateInstance) {
                        $selectedMatch               = $candidate
                        $settingInstanceObj          = $candidateInstance
                        $foundDefButNeedsCustomerInfo = $false
                        break
                    }
                }

                if ($settingInstanceObj) {
                    $definitionId = [string]$settingInstanceObj.settingDefinitionId

                    if ($definitionId -and $graphSettingsByDefinitionId.ContainsKey($definitionId)) {
                        $existingInstance = $graphSettingsByDefinitionId[$definitionId]
                        $existingJson = $existingInstance | ConvertTo-Json -Depth 25 -Compress
                        $incomingJson = $settingInstanceObj | ConvertTo-Json -Depth 25 -Compress

                        if ($existingJson -eq $incomingJson) {
                            [void]$processedSettingNames.Add($settingDedupKey)
                            Write-Host "  Duplicate definition skipped: $($setting.SettingName) -> $definitionId (same value)" -ForegroundColor DarkGray
                            continue
                        }

                        $unmappedSettings += $setting
                        Write-Host "  DEFINITION COLLISION: $($setting.SettingName) maps to existing definition ID '$definitionId' with a different value (CIS $($setting.CISReference))" -ForegroundColor Yellow
                        continue
                    }

                    $graphSettings += @{
                        '@odata.type'   = '#microsoft.graph.deviceManagementConfigurationSetting'
                        settingInstance = $settingInstanceObj
                    }
                    if ($definitionId) { $graphSettingsByDefinitionId[$definitionId] = $settingInstanceObj }
                    [void]$processedSettingNames.Add($settingDedupKey)
                    $siblingNote = if ($siblingValues.Count -gt 0) { " (+$($siblingValues.Count) sibling value(s))" } else { '' }
                    Write-Host "  Mapped: $($setting.SettingName) -> $($selectedMatch.displayName) [$($setting.SettingValue)]$siblingNote" -ForegroundColor DarkGray
                }
                elseif ($foundDefButNeedsCustomerInfo) {
                    $unmappedSettings += $setting
                    Write-Host "  CUSTOMER INFO MISSING: $($setting.SettingName) (CIS $($setting.CISReference)) - setting found as '$($selectedMatch.displayName)' but requires customer-provided values (e.g. site list, URL patterns)" -ForegroundColor Yellow
                }
                else {
                    $unmappedSettings += $setting
                    Write-Host "  VALUE MISMATCH: $($setting.SettingName) - could not match value '$($setting.SettingValue)' in any matching definition (CIS $($setting.CISReference))" -ForegroundColor DarkYellow
                    $sampleDef = $null
                    if ($orderedDefinitions.Count -gt 0) {
                        $sampleDef = Get-SettingDefinitionById -DefinitionId $orderedDefinitions[0].id
                        if (-not $sampleDef) { $sampleDef = $orderedDefinitions[0] }
                    }
                    if ($sampleDef -and $sampleDef.options) {
                        $optionList = ($sampleDef.options | ForEach-Object { "    '$($_.displayName)' (itemId: $($_.itemId))" }) -join "`n"
                        Write-Host "    Available options (first candidate):`n$optionList" -ForegroundColor DarkGray
                    }
                }
            }
            else {
                $unmappedSettings += $setting
                $notFoundInIntune += [PSCustomObject]@{
                    CISReference = $setting.CISReference
                    SettingName  = $setting.SettingName
                    PolicyName   = $policy.PolicyName
                }
                $notFoundMsg = "  NOT FOUND IN INTUNE: $($setting.SettingName) (CIS $($setting.CISReference))"
                if ($ProductIdPattern) { $notFoundMsg += " - no matching '$ProductIdPattern' definition found in Settings Catalog" }
                Write-Host $notFoundMsg -ForegroundColor DarkYellow
            }
        }

        if ($unmappedSettings.Count -gt 0) {
            Write-Host "  Warning: $($unmappedSettings.Count) setting(s) could not be mapped to Settings Catalog definitions" -ForegroundColor Yellow
            Write-Host "  These settings need manual configuration after policy creation" -ForegroundColor Yellow
        }

        if ($graphSettings.Count -eq 0) {
            $notFoundCount = ($unmappedSettings | Where-Object { $notFoundInIntune.CISReference -contains $_.CISReference }).Count
            if ($notFoundCount -eq $unmappedSettings.Count) {
                Write-Host "  SKIPPED: '$($policy.PolicyName)' - $notFoundCount setting(s) could not be found in Intune Settings Catalog" -ForegroundColor Yellow
            } else {
                Write-Host "  SKIPPED: No settings could be mapped for '$($policy.PolicyName)' - all $($unmappedSettings.Count) setting(s) need manual configuration" -ForegroundColor Yellow
            }
            $failed++
            $failedPolicies += $policy.PolicyName
            continue
        }

        $actionWord = if ($policyExists) { 'Update Settings Catalog policy' } else { 'Create Settings Catalog policy' }
        if ($PSCmdlet.ShouldProcess($policy.PolicyName, $actionWord)) {
            $description = $policy.Description
            if ($unmappedSettings.Count -gt 0) {
                $unmappedRefs = ($unmappedSettings | ForEach-Object { $_.CISReference }) -join ', '
                $description += " | Manual config needed for: $unmappedRefs"
            }

            if ($policyExists) {
                $existingId = $existingPolicyObj.id
                $success    = Update-SettingsCatalogPolicy `
                    -PolicyId    $existingId `
                    -PolicyName  $policy.PolicyName `
                    -Description $description `
                    -Platform    $Platform `
                    -Settings    $graphSettings

                if ($success) {
                    Write-Host "  UPDATED: $($policy.PolicyName) (ID: $existingId)" -ForegroundColor Green
                    $updated++
                } else {
                    Write-Host "  FAILED: $($policy.PolicyName)" -ForegroundColor Red
                    $failed++
                    $failedPolicies += $policy.PolicyName
                }
            }
            else {
                $result = New-SettingsCatalogPolicy `
                    -PolicyName  $policy.PolicyName `
                    -Description $description `
                    -Platform    $Platform `
                    -Settings    $graphSettings

                if ($result) {
                    Write-Host "  CREATED: $($policy.PolicyName) (ID: $($result.id))" -ForegroundColor Green
                    $created++
                } else {
                    Write-Host "  FAILED: $($policy.PolicyName)" -ForegroundColor Red
                    $failed++
                    $failedPolicies += $policy.PolicyName
                }
            }
        }
    }

    # Summary
    Write-Host ""
    Write-Host "============================================" -ForegroundColor Cyan
    Write-Host "  Results" -ForegroundColor Cyan
    Write-Host "============================================" -ForegroundColor Cyan
    Write-Host "  Created:  $created"
    Write-Host "  Updated:  $updated"
    Write-Host "  Skipped:  $skipped (already exist)"
    Write-Host "  Failed:   $failed"
    Write-Host "  Total:    $($policyData.Count)"
    Write-Host ""

    if ($failed -gt 0) {
        Write-Host "Policies not created:" -ForegroundColor Yellow
        foreach ($fp in $failedPolicies) { Write-Host "  - $fp" -ForegroundColor Red }
        Write-Host ""
    }

    if (-not $isIosTemplateMode -and $notFoundInIntune.Count -gt 0) {
        Write-Host "Settings not found in Intune Settings Catalog ($($notFoundInIntune.Count)):" -ForegroundColor Yellow
        $byPolicy = $notFoundInIntune | Group-Object PolicyName
        foreach ($grp in $byPolicy) {
            Write-Host "  Policy: $($grp.Name)" -ForegroundColor DarkGray
            foreach ($nf in $grp.Group) {
                Write-Host "    CIS $($nf.CISReference): $($nf.SettingName)" -ForegroundColor Red
            }
        }
        Write-Host ""
    }

    Write-Host "TIP: After creation, open the Intune portal to review and configure any" -ForegroundColor Yellow
    if ($isIosTemplateMode) {
        Write-Host "     iOS template settings that could not be automatically mapped." -ForegroundColor Yellow
    } else {
        Write-Host "     settings that could not be automatically mapped." -ForegroundColor Yellow
    }
    Write-Host ""

} else {

    # ══════════════════════════════════════════════════════════════════════════
    #  GUI Mode
    # ══════════════════════════════════════════════════════════════════════════

    Add-Type -AssemblyName PresentationFramework, PresentationCore, WindowsBase
    Add-Type -AssemblyName System.Windows.Forms

    # Capture this script's own path so the Export/Create buttons can spawn
    # themselves in CLI mode (with -MdFilePath) as a subprocess.
    $script:thisScriptPath = $PSCommandPath

    #region RecItem class for DataGrid checkbox binding
    $_recItemType = 'RecItem' -as [type]
    if (-not $_recItemType -or -not $_recItemType.GetProperty('IsManual')) {
        if ($_recItemType) {
            [System.Windows.MessageBox]::Show(
                "A previous version of RecItem is loaded in this session.`nPlease close and re-open the script in a new PowerShell window.",
                'Restart Required', 'OK', 'Warning')
            return
        }
        Add-Type -Language CSharp @'
using System.ComponentModel;
public class RecItem : INotifyPropertyChanged
{
    private bool _selected;
    public bool Selected
    {
        get { return _selected; }
        set { _selected = value; OnPropertyChanged("Selected"); }
    }
    public string CISRef      { get; set; }
    public string SettingName  { get; set; }
    public string SettingValue { get; set; }
    public string PolicyName   { get; set; }
    public string Profile      { get; set; }
    public string Recommendation { get; set; }
    public string Notes        { get; set; }
    public bool   IsManual     { get; set; }

    public event PropertyChangedEventHandler PropertyChanged;
    protected void OnPropertyChanged(string name)
    {
        if (PropertyChanged != null)
            PropertyChanged(this, new PropertyChangedEventArgs(name));
    }
}
'@
    }
    #endregion

    #region XAML
    [xml]$xaml = @"
<Window
    xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"
    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"
    Title="CIS Benchmark - Intune Policy Creator"
    Width="880" Height="920"
    WindowStartupLocation="CenterScreen"
    ResizeMode="CanResizeWithGrip"
    Background="#F0F0F0">
