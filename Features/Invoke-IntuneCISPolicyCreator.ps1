            [System.Windows.MessageBox]::Show('No settings selected. Check at least one setting in the list.', 'No Selection', 'OK', 'Warning')
            return
        }

        $selectedPolicies = @($selectedItems | ForEach-Object { $_.PolicyName } | Sort-Object -Unique)
        $selectedRefs     = @($selectedItems | Where-Object { $_.CISRef -and $_.CISRef -ne '-' } | ForEach-Object { $_.CISRef })
        $selectedRecTexts = @($selectedItems | Where-Object { -not $_.CISRef -or $_.CISRef -eq '-' } | ForEach-Object { $_.Recommendation })
        $manualPolicies   = @($manualItems   | ForEach-Object { $_.PolicyName } | Sort-Object -Unique)
        $manualSummary    = @()
        foreach ($mp in $manualPolicies) {
            $manualSummary += "  MANUAL: $mp"
            foreach ($s in @($manualItems | Where-Object { $_.PolicyName -eq $mp })) {
                $manualSummary += "          - [$($s.CISRef)] $($s.SettingName)"
            }
        }

