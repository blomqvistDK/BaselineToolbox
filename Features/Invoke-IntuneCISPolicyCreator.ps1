        Write-Log "MD: $mdPath"
        Write-Log "Profile: $profileLevel | Platform: $platform"
        if ($manualPolicies.Count -gt 0) {
            Write-Log "Skipping $($manualItems.Count) settings requiring company specific data"
        }
        Write-Log ""

        $runspace = [runspacefactory]::CreateRunspace()
        $runspace.ApartmentState = 'STA'
        $runspace.Open()
        $runspace.SessionStateProxy.SetVariable('arguments',         $arguments)
        $runspace.SessionStateProxy.SetVariable('txtLog',            $txtLog)
        $runspace.SessionStateProxy.SetVariable('progressBar',       $progressBar)
        $runspace.SessionStateProxy.SetVariable('txtProgress',       $txtProgress)
        $runspace.SessionStateProxy.SetVariable('btnExportOnly',     $btnExportOnly)
        $runspace.SessionStateProxy.SetVariable('btnCreatePolicies', $btnCreatePolicies)
        $runspace.SessionStateProxy.SetVariable('btnBrowseMd',       $btnBrowseMd)
        $runspace.SessionStateProxy.SetVariable('btnOpenJson',       $btnOpenJson)
        $runspace.SessionStateProxy.SetVariable('expectedJsonPath',  $expectedJsonPath)
        $runspace.SessionStateProxy.SetVariable('window',            $window)
        $runspace.SessionStateProxy.SetVariable('manualSummary',     $manualSummary)

        $ps = [powershell]::Create()
        $ps.Runspace = $runspace
        $ps.AddScript({
            function Write-Log {
                param([string]$Message)
                $txtLog.Dispatcher.Invoke([Action]{ $txtLog.AppendText("$Message`r`n"); $txtLog.ScrollToEnd() })
            }
            function Reset-Buttons {
                $btnExportOnly.Dispatcher.Invoke([Action]{
                    $btnExportOnly.IsEnabled     = $true
                    $btnExportOnly.Content       = [char]0x1F4E4 + ' Export JSON'
                    $btnCreatePolicies.IsEnabled = $true
                    $btnBrowseMd.IsEnabled       = $true
                })
            }
            function Set-ProgressDone {
                $progressBar.Dispatcher.Invoke([Action]{ $progressBar.IsIndeterminate = $false; $progressBar.Value = 100 })
                $txtProgress.Dispatcher.Invoke([Action]{ $txtProgress.Text = 'Done' })
            }
            function Set-ProgressError {
                $progressBar.Dispatcher.Invoke([Action]{ $progressBar.IsIndeterminate = $false; $progressBar.Value = 0 })
                $txtProgress.Dispatcher.Invoke([Action]{ $txtProgress.Text = 'Error' })
            }
            try {
                $process = [System.Diagnostics.Process]::new()
                $process.StartInfo.FileName               = 'powershell.exe'
                $process.StartInfo.Arguments              = ($arguments | ForEach-Object { if ($_ -match '\s') { "`"$_`"" } else { $_ } }) -join ' '
                $process.StartInfo.UseShellExecute        = $false
                $process.StartInfo.RedirectStandardOutput = $true
                $process.StartInfo.RedirectStandardError  = $true
                $process.StartInfo.CreateNoWindow         = $true
                $process.StartInfo.StandardOutputEncoding = [System.Text.Encoding]::UTF8
                $process.StartInfo.StandardErrorEncoding  = [System.Text.Encoding]::UTF8
                $process.Start() | Out-Null

                while (-not $process.StandardOutput.EndOfStream) {
                    $line = $process.StandardOutput.ReadLine()
                    if ($line) { Write-Log $line }
                }
                $stderr = $process.StandardError.ReadToEnd()
                if ($stderr) {
                    foreach ($errLine in ($stderr -split "`n")) {
                        if ($errLine.Trim()) { Write-Log "ERROR: $($errLine.Trim())" }
                    }
                }
                $process.WaitForExit()

