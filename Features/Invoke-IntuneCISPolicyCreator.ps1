function Test-NameSimilarity {
    <#
    .SYNOPSIS
        Returns $true if the catalog display name shares enough meaningful words with
        the CIS setting name to be considered a valid match.
    #>
    param([string]$CISName, [string]$CatalogName)

    $skipWords = [System.Collections.Generic.HashSet[string]]@(
        'the','for','and','all','set','with','from','that','this','not','are','use',
        'has','its','can','how','new','per','by','an','a','or','of','to','in','on',
        'is','be','do','if','it','at','as','up','these','those','their','them'
    )

    function Get-Words([string]$text) {
        return @(($text -split '\W+') |
            Where-Object { $_.Length -ge 3 -and ($_.ToLower() -notin $skipWords) } |
            ForEach-Object { $_.ToLower() })
    }

    $cisWords = Get-Words $CISName
    $catWords = Get-Words $CatalogName
    if ($cisWords.Count -eq 0) { return $true }

    $matchCount = 0
    foreach ($word in $cisWords) {
        if ($catWords | Where-Object { $_ -eq $word -or $_.Contains($word) -or $word.Contains($_) }) {
            $matchCount++
        }
    }

    $required = if ($cisWords.Count -le 2) { 1 } else { 2 }
    return ($matchCount -ge $required)
}

