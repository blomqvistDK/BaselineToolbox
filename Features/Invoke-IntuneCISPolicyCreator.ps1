            function Set-ProgressDone {
                $progressBar.Dispatcher.Invoke([Action]{ $progressBar.IsIndeterminate = $false; $progressBar.Value = 100 })
                $txtProgress.Dispatcher.Invoke([Action]{ $txtProgress.Text = 'Completed' })
            }
            function Set-ProgressError {
                $progressBar.Dispatcher.Invoke([Action]{ $progressBar.IsIndeterminate = $false; $progressBar.Value = 0 })
                $txtProgress.Dispatcher.Invoke([Action]{ $txtProgress.Text = 'Error' })
            }

            try {
                $process = [System.Diagnostics.Process]::new()
                $process.StartInfo.FileName               = 'powershell.exe'
                $process.StartInfo.Arguments              = ($arguments | ForEach-Object { if ($_ -match '\s') { "`"$_`"" } else { $_ } }) -join ' '
                $process.StartInfo.UseShellExecute        = $false
                $process.StartInfo.RedirectStandardOutput = $true
                $process.StartInfo.RedirectStandardError  = $true
                $process.StartInfo.CreateNoWindow         = $true
                $process.StartInfo.StandardOutputEncoding = [System.Text.Encoding]::UTF8
                $process.StartInfo.StandardErrorEncoding  = [System.Text.Encoding]::UTF8
                $process.Start() | Out-Null

                $allOutputLines = [System.Collections.Generic.List[string]]::new()
                $createdCount   = 0
                while (-not $process.StandardOutput.EndOfStream) {
                    $line = $process.StandardOutput.ReadLine()
                    if ($line) {
                        Write-Log $line
                        $allOutputLines.Add($line)
                        if ($line -match 'CREATED:|SKIP:|FAILED:') {
                            $createdCount++
                            if ($policyCount -gt 0) {
                                $pct = [math]::Min(100, [math]::Round(($createdCount / $policyCount) * 100))
                                $progressBar.Dispatcher.Invoke([Action]{ $progressBar.IsIndeterminate = $false; $progressBar.Value = $pct })
                                $txtProgress.Dispatcher.Invoke([Action]{ $txtProgress.Text = "$createdCount / $policyCount policies" })
                            }
                        }
                        elseif ($line -match 'Connecting to Microsoft Graph') {
                            $txtProgress.Dispatcher.Invoke([Action]{ $txtProgress.Text = 'Waiting for Graph sign-in...' })
                        }
                        elseif ($line -match 'Connected to Microsoft Graph') {
                            $txtProgress.Dispatcher.Invoke([Action]{ $txtProgress.Text = 'Connected - creating policies...' })
                            $progressBar.Dispatcher.Invoke([Action]{ $progressBar.IsIndeterminate = $false; $progressBar.Value = 0 })
                        }
                    }
                }

                $stderr = $process.StandardError.ReadToEnd()
                if ($stderr) {
                    foreach ($errLine in ($stderr -split "`n")) {
                        if ($errLine.Trim()) { Write-Log "ERROR: $($errLine.Trim())" }
                    }
                }
                $process.WaitForExit()

                if ($process.ExitCode -eq 0) {
                    Write-Log ""
                    Write-Log "=== Policy creation completed ==="
                    if ($manualSummary -and $manualSummary.Count -gt 0) {
                        Write-Log ""
                        Write-Log "=== Policies requiring manual creation (company specific data needed) ==="
                        foreach ($ml in $manualSummary) { Write-Log $ml }
                    }

                    # Build HTML report from parsed output
                    $reportRows = [System.Collections.Generic.List[pscustomobject]]::new()

                    $mappedLines       = @($allOutputLines | Where-Object { $_ -match '\s+Mapped:\s+(.+)\s+->\s+(.+)\[' })
                    $notFoundLines     = @($allOutputLines | Where-Object { $_ -match 'NOT FOUND IN INTUNE:' })
                    $mismatchLines     = @($allOutputLines | Where-Object { $_ -match 'VALUE MISMATCH:' })
                    $customerInfoLines = @($allOutputLines | Where-Object { $_ -match 'CUSTOMER INFO MISSING:' })

                    $mappedSettings = [System.Collections.Generic.HashSet[string]]::new()
                    foreach ($ml in $mappedLines) {
                        if ($ml -match 'Mapped:\s+(.+?)\s+->') { $mappedSettings.Add($Matches[1].Trim()) | Out-Null }
                    }
                    $notFoundSettings = [System.Collections.Generic.HashSet[string]]::new()
                    foreach ($nl in $notFoundLines) {
                        if ($nl -match 'NOT FOUND IN INTUNE:\s+(.+?)\s+\(CIS') { $notFoundSettings.Add($Matches[1].Trim()) | Out-Null }
                    }
                    $mismatchSettings = [System.Collections.Generic.HashSet[string]]::new()
                    foreach ($mm in $mismatchLines) {
                        if ($mm -match 'VALUE MISMATCH:\s+(.+?)\s+-') { $mismatchSettings.Add($Matches[1].Trim()) | Out-Null }
                    }
                    $customerInfoSettings = [System.Collections.Generic.HashSet[string]]::new()
                    foreach ($ci in $customerInfoLines) {
                        if ($ci -match 'CUSTOMER INFO MISSING:\s+(.+?)\s+\(CIS') { $customerInfoSettings.Add($Matches[1].Trim()) | Out-Null }
                    }

                    foreach ($si in $selectedItemsForReport) {
                        $outcome = if     ($customerInfoSettings.Contains($si.SettingName)) { 'CustomerInfoMissing' }
                                   elseif ($notFoundSettings.Contains($si.SettingName))     { 'NotFound' }
                                   elseif ($mismatchSettings.Contains($si.SettingName))     { 'ValueMismatch' }
                                   elseif ($mappedSettings.Contains($si.SettingName))       { 'Created' }
                                   else { 'NotFound' }
                        $detail  = if ($outcome -eq 'CustomerInfoMissing') { 'Setting found in Intune but requires customer-provided values (e.g. site list, URL patterns)' } else { '' }
                        $reportRows.Add([pscustomobject]@{
                            PolicyName   = $si.PolicyName
                            CISRef       = $si.CISRef
                            SettingName  = $si.SettingName
                            SettingValue = $si.SettingValue
                            Profile      = $si.Profile
                            Outcome      = $outcome
                            Detail       = $detail
                        })
                    }
                    foreach ($mi in $manualItemsForReport) {
                        $reportRows.Add([pscustomobject]@{
                            PolicyName   = $mi.PolicyName
                            CISRef       = $mi.CISRef
                            SettingName  = $mi.SettingName
                            SettingValue = $mi.SettingValue
                            Profile      = $mi.Profile
                            Outcome      = 'Manual'
                            Detail       = 'Customer-specific data required'
                        })
                    }

                    $htmlReportPath  = [System.IO.Path]::ChangeExtension($mdPathForReport, '.creation-report.html')
                    try {
                        $reportRowsCopy  = @($reportRows)
                        $mdFileNameLocal = [System.IO.Path]::GetFileName($mdPathForReport)
                        $htmlPathLocal   = $htmlReportPath
                        $pfLocal         = $profileLevelForReport
                        $platLocal       = $platformForReport
                        $window.Dispatcher.Invoke([Action]{
                            Add-Type -AssemblyName System.Web -ErrorAction SilentlyContinue
                            & $buildHtmlReportSb `
                                -OutputPath  $htmlPathLocal `
                                -MdFileName  $mdFileNameLocal `
                                -ProfileLevel $pfLocal `
                                -Platform     $platLocal `
                                -ReportRows   $reportRowsCopy
                        })
                        Write-Log "HTML report: $htmlReportPath"
                        $btnOpenReport.Dispatcher.Invoke([Action]{ $btnOpenReport.IsEnabled = $true })
                        $window.Dispatcher.Invoke([Action]{ $window.Tag = @{ ReportPath = $htmlReportPath } })
                    } catch {
                        Write-Log "Could not generate HTML report: $($_.Exception.Message)"
                    }

                    Set-ProgressDone
                } else {
                    Write-Log ""
                    Write-Log "=== Policy creation finished with errors (exit code: $($process.ExitCode)) ==="
                    Set-ProgressError
                }
            }
            catch {
                Write-Log "ERROR: $($_.Exception.Message)"
                Set-ProgressError
            }
            finally {
                Reset-Buttons
            }
        }) | Out-Null
        $ps.BeginInvoke() | Out-Null
    })

